create or replace function public.is_store_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.admin_users
    where user_id = (select auth.uid())
  );
$$;

create or replace function public.consume_public_rate_limit(
  p_identifier text,
  p_max_requests integer,
  p_window_seconds integer
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_count integer;
  current_window timestamptz;
begin
  if p_identifier !~ '^[a-f0-9]{64}$'
     or p_max_requests < 1
     or p_window_seconds < 1 then
    return false;
  end if;

  insert into public.api_rate_limits (identifier, window_started_at, request_count)
  values (p_identifier, now(), 1)
  on conflict (identifier) do update set
    window_started_at = case
      when public.api_rate_limits.window_started_at
        <= now() - make_interval(secs => p_window_seconds)
      then now()
      else public.api_rate_limits.window_started_at
    end,
    request_count = case
      when public.api_rate_limits.window_started_at
        <= now() - make_interval(secs => p_window_seconds)
      then 1
      else public.api_rate_limits.request_count + 1
    end
  returning request_count, window_started_at into current_count, current_window;

  if substring(p_identifier from 1 for 2) in ('00', '20', '40', '60', '80', 'a0', 'c0', 'e0') then
    delete from public.api_rate_limits
    where window_started_at < now() - interval '1 day';
  end if;

  return current_count <= p_max_requests;
end;
$$;

