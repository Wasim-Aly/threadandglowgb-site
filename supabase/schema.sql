create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 120),
  description text not null default '' check (char_length(description) <= 2000),
  category text not null check (category in ('Salt Lamps', 'Crochet Bags', 'Flowers & Decor', 'Keychains')),
  image_url text not null default '' check (char_length(image_url) <= 500),
  price numeric(12, 2) check (price is null or price >= 0),
  stock integer check (stock is null or stock >= 0),
  is_active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text not null unique default (
    'TG-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8))
  ),
  customer_name text not null check (char_length(customer_name) between 1 and 120),
  contact_method text not null check (contact_method in ('whatsapp', 'email')),
  contact_value text not null check (char_length(contact_value) between 5 and 254),
  city text not null check (char_length(city) between 1 and 120),
  delivery_address text not null default '' check (char_length(delivery_address) <= 500),
  notes text not null default '' check (char_length(notes) <= 1000),
  requested_via text not null check (requested_via in ('whatsapp', 'email')),
  items jsonb not null check (jsonb_typeof(items) = 'array' and jsonb_array_length(items) between 1 and 20),
  estimated_total numeric(12, 2) check (estimated_total is null or estimated_total >= 0),
  status text not null default 'new' check (status in ('new', 'reviewing', 'confirmed', 'fulfilled', 'cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.inquiries (
  id uuid primary key default gen_random_uuid(),
  inquiry_number text not null unique default (
    'TG-M-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8))
  ),
  customer_name text not null check (char_length(customer_name) between 1 and 120),
  reply_contact text not null default '' check (char_length(reply_contact) <= 254),
  requested_via text not null check (requested_via in ('whatsapp', 'email')),
  message text not null check (char_length(message) between 1 and 2000),
  status text not null default 'new' check (status in ('new', 'replied', 'closed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.api_rate_limits (
  identifier text primary key check (char_length(identifier) = 64),
  window_started_at timestamptz not null,
  request_count integer not null check (request_count > 0)
);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists products_set_updated_at on public.products;
create trigger products_set_updated_at before update on public.products
for each row execute function public.set_updated_at();

drop trigger if exists orders_set_updated_at on public.orders;
create trigger orders_set_updated_at before update on public.orders
for each row execute function public.set_updated_at();

drop trigger if exists inquiries_set_updated_at on public.inquiries;
